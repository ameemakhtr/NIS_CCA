from typing import List, Dict, Any
import json
from cca_cipher import AlKindiCompositeCipher, clean_text, prepare_playfair_digraphs


CHALLENGE_PLAINTEXTS = [
    # Pair 1: Correct
    "DEFEND THE PERIMETER AT ONCE",
    # Pair 2: Correct
    "ZERO TRUST ARCHITECTURE SECURES DATA",
    # Pair 3: INCORRECT (Targeted single-character perturbation)
    "CRYPTOGRAPHIC PROTOCOL FAILURE DETECTED",
    # Pair 4: Correct
    "INCIDENT RESPONSE TEAM ENGAGED IMMEDIATELY",
    # Pair 5: Correct
    "QUANTUM COMPUTING THREATENS TRADITIONAL RSA",
    # Pair 6: INCORRECT (Transposition parity fault in Stage 3)
    "MALWARE EXFILTRATING SENSITIVE AUDIT LOGS",
    # Pair 7: Correct
    "FIREWALL BLOCKS UNTRUSTED NETWORK TRAFFIC",
    # Pair 8: Correct
    "AUTHENTICATION TOKEN EXPIRES SOON REFRESH",
    # Pair 9: INCORRECT (Tail desynchronization & wrong modular constant)
    "DENIAL OF SERVICE ATTACK FLOODS ROUTER",
    # Pair 10: Correct
    "ELLIPTIC CURVE DIGITAL SIGNATURE STANDARD"
]


def generate_challenge_dataset() -> Dict[str, Any]:
    """
    Generates the complete 10-pair challenge dataset.
    Returns:
      A dictionary with:
        - pairs: list of 10 pairs (id, plaintext, ciphertext)
        - ground_truth: validation metadata for each pair (valid/invalid, reason)
    """
    cipher = AlKindiCompositeCipher(
        playfair_key="LABYRINTH",
        vigenere_key="VALIANT",
        delta=3,
        theta=7
    )

    dataset_pairs = []
    ground_truth = []

    for idx, pt in enumerate(CHALLENGE_PLAINTEXTS, start=1):
        ct_genuine, trace = cipher.encrypt(pt)

        if idx == 3:
            # Corruption Type A: Single-character off-by-one substitution at index 5
            corrupted_chars = list(ct_genuine)
            orig_char = corrupted_chars[5]
            tampered_char = chr((ord(orig_char) - 65 + 4) % 26 + 65)
            corrupted_chars[5] = tampered_char
            ct_final = "".join(corrupted_chars)
            is_valid = False
            corruption_reason = (
                f"Tampered at index 5: changed '{orig_char}' to '{tampered_char}' (+4 shift). "
                "Violates Playfair rectangle/row-column relation and Vigenere periodic congruence."
            )

        elif idx == 6:
            # Corruption Type B: Transposition parity corruption
            # Stage 3 specifies swapping characters in EVEN blocks (0, 2, 4...).
            # Here we swap characters in an ODD block (block 1: indices 2 and 3), violating parity.
            corrupted_chars = list(ct_genuine)
            corrupted_chars[2], corrupted_chars[3] = corrupted_chars[3], corrupted_chars[2]
            ct_final = "".join(corrupted_chars)
            is_valid = False
            corruption_reason = (
                "Transposition parity violation: Characters at indices 2 and 3 (block 1, odd) "
                "were swapped instead of maintaining the even-block parity rule."
            )

        elif idx == 9:
            # Corruption Type C: Tail desynchronization corruption
            corrupted_chars = list(ct_genuine)
            for k in range(len(corrupted_chars) - 4, len(corrupted_chars)):
                corrupted_chars[k] = chr((ord(corrupted_chars[k]) - 65 + 11) % 26 + 65)
            ct_final = "".join(corrupted_chars)
            is_valid = False
            corruption_reason = (
                "Tail desynchronization: The last 4 ciphertext characters were arbitrarily shifted by +11 mod 26, "
                "causing algebraic stream failure and invalid digram reversal."
            )

        else:
            ct_final = ct_genuine
            is_valid = True
            corruption_reason = "GENUINE - Mathematically consistent with all 3 cipher tiers."

        dataset_pairs.append({
            "pair_id": idx,
            "plaintext": pt,
            "cleaned_prepared": trace["prepared_plaintext"],
            "ciphertext": ct_final,
            "length": len(ct_final)
        })

        ground_truth.append({
            "pair_id": idx,
            "is_valid": is_valid,
            "genuine_ciphertext": ct_genuine,
            "challenge_ciphertext": ct_final,
            "reason": corruption_reason,
            "trace": trace
        })

    return {
        "cipher_info": {
            "name": "Al-Kindi Tri-Tiered Composite Cipher (KTCC)",
            "historical_basis": "Named after Abu Yusuf Al-Kindi (801-873 CE), Father of Cryptanalysis",
            "playfair_key": "LABYRINTH",
            "vigenere_key": "VALIANT",
            "delta": 3,
            "theta": 7
        },
        "pairs": dataset_pairs,
        "ground_truth": ground_truth
    }


def export_challenge_markdown(data: Dict[str, Any]) -> str:
    """Format the 10 challenge pairs as a clean markdown table."""
    md = []
    md.append("# CT-486 Classical Cipher Challenge: Challenge Dataset")
    md.append("### Al-Kindi Tri-Tiered Composite Cipher (KTCC)")
    md.append("### Provided to Red Team for Cryptanalysis")
    md.append("")
    md.append("| Pair # | Plaintext | Ciphertext | Length |")
    md.append("|:------:|:----------------------------------------------|:------------------------------------------------|:------:|")
    for p in data["pairs"]:
        md.append(f"| **{p['pair_id']}** | `{p['plaintext']}` | `{p['ciphertext']}` | {p['length']} |")
    md.append("")
    md.append("> **Note for Red Team:** Exactly 7 of the pairs above are genuine outputs of the hidden cipher. "
              "Exactly 3 pairs are intentionally corrupted. Your task is to identify the 3 invalid pairs, "
              "recover the keys and encryption sequence, and prove your cryptanalysis with formal evidence.")
    return "\n".join(md)


if __name__ == "__main__":
    challenge_data = generate_challenge_dataset()
    print(export_challenge_markdown(challenge_data))
    with open("challenge_dataset.json", "w", encoding="utf-8") as f:
        json.dump(challenge_data, f, indent=2)
    print("\nDataset successfully exported to challenge_dataset.json")
